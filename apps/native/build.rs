//! Build-time art and the app icon.
//!
//! The Haze portraits are full-colour vector art and GPUI's `svg()` element
//! draws an SVG as a single tint, so they cannot be shown that way. This script
//! rasterises each portrait (and each coding agent's logo) to a PNG once, at
//! twice the largest size the window draws it, and generates a lookup table the
//! window `include!`s. Nothing here runs at startup.
//!
//! The source files belong to the React app (`apps/desktop/src`); they are read,
//! never written.

use std::path::{Path, PathBuf};
use std::{env, fs};

/// 2× the largest portrait the window draws (64 px on a Team page card).
const PORTRAIT_PX: u32 = 128;
/// 2× the largest logo the window draws (80% of 64 px, rounded up).
const LOGO_PX: u32 = 96;

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let repo = manifest
        .parent()
        .and_then(Path::parent)
        .expect("apps/native is two folders below the repository root")
        .to_path_buf();
    let out = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));
    let desktop = repo.join("apps").join("desktop").join("src");

    let portraits = rasterise_portraits(&desktop.join("blob").join("haze").join("characters"), &out);
    let logos = rasterise_logos(&desktop.join("assets").join("providers"), &out);
    write_assets(&out, &portraits, &logos);

    embed_icon(&repo, &out);
}

/// Every `characters/<slug>/avatar.svg` as `<slug>.png`.
fn rasterise_portraits(folder: &Path, out: &Path) -> Vec<String> {
    let mut names: Vec<String> = Vec::new();
    let Ok(entries) = fs::read_dir(folder) else {
        println!("cargo:warning=the Haze portraits were not found at {}; portraits will show as initials", folder.display());
        return names;
    };
    let mut slugs: Vec<String> = entries
        .filter_map(|entry| entry.ok())
        .filter(|entry| entry.path().is_dir())
        .filter(|entry| entry.path().join("avatar.svg").is_file())
        .filter_map(|entry| entry.file_name().into_string().ok())
        .collect();
    slugs.sort();
    for slug in slugs {
        let svg = folder.join(&slug).join("avatar.svg");
        println!("cargo:rerun-if-changed={}", svg.display());
        let png = render(&svg, PORTRAIT_PX);
        fs::write(out.join(format!("{slug}.png")), png).expect("writing a rasterised portrait");
        names.push(slug);
    }
    names
}

/// Every `assets/providers/*.svg` as `<file>.png` (claude, codex-dark, …).
fn rasterise_logos(folder: &Path, out: &Path) -> Vec<String> {
    let mut names: Vec<String> = Vec::new();
    let Ok(entries) = fs::read_dir(folder) else {
        println!("cargo:warning=the coding-agent logos were not found at {}; bots will show initials", folder.display());
        return names;
    };
    let mut files: Vec<(String, PathBuf)> = entries
        .filter_map(|entry| entry.ok())
        .filter(|entry| entry.path().is_file())
        .filter_map(|entry| {
            let path = entry.path();
            let stem = path.file_stem()?.to_str()?.to_owned();
            (path.extension()? == "svg").then_some((stem, path))
        })
        .collect();
    files.sort();
    for (stem, path) in files {
        println!("cargo:rerun-if-changed={}", path.display());
        let png = render(&path, LOGO_PX);
        fs::write(out.join(format!("logo-{stem}.png")), png).expect("writing a rasterised logo");
        names.push(stem);
    }
    names
}

/// `art_assets.rs`: a `char-*` id (or a provider logo file name) to PNG bytes.
fn write_assets(out: &Path, portraits: &[String], logos: &[String]) {
    let mut source = String::from(
        "// Generated by build.rs. A portrait or a coding agent's logo, rasterised once.\n\n",
    );
    source.push_str("pub fn portrait(id: &str) -> Option<&'static [u8]> {\n    match id {\n");
    for slug in portraits {
        source.push_str(&format!(
            "        \"char-{slug}\" => Some(include_bytes!(concat!(env!(\"OUT_DIR\"), \"/{slug}.png\"))),\n",
        ));
    }
    source.push_str("        _ => None,\n    }\n}\n\n");
    source.push_str("pub fn portrait_ids() -> &'static [&'static str] {\n    &[\n");
    for slug in portraits {
        source.push_str(&format!("        \"char-{slug}\",\n"));
    }
    source.push_str("    ]\n}\n\n");
    source.push_str("pub fn logo(name: &str) -> Option<&'static [u8]> {\n    match name {\n");
    for stem in logos {
        source.push_str(&format!(
            "        \"{stem}\" => Some(include_bytes!(concat!(env!(\"OUT_DIR\"), \"/logo-{stem}.png\"))),\n",
        ));
    }
    source.push_str("        _ => None,\n    }\n}\n");
    fs::write(out.join("art_assets.rs"), source).expect("writing the generated art table");
    println!("cargo:rerun-if-changed={}", out.join("art_assets.rs").display());
}

/// Render one SVG to a square RGBA PNG, centred and never stretched.
fn render(svg: &Path, size: u32) -> Vec<u8> {
    let data = fs::read(svg).unwrap_or_else(|error| panic!("reading {}: {error}", svg.display()));
    let tree = resvg::usvg::Tree::from_data(&data, &resvg::usvg::Options::default())
        .unwrap_or_else(|error| panic!("parsing {} as SVG: {error}", svg.display()));
    let source = tree.size();
    let scale = (size as f32 / source.width()).min(size as f32 / source.height());
    let mut pixmap = resvg::tiny_skia::Pixmap::new(size, size)
        .unwrap_or_else(|| panic!("allocating a {size}×{size} pixmap for {}", svg.display()));
    let transform = resvg::tiny_skia::Transform::from_scale(scale, scale).post_translate(
        (size as f32 - source.width() * scale) / 2.0,
        (size as f32 - source.height() * scale) / 2.0,
    );
    resvg::render(&tree, transform, &mut pixmap.as_mut());

    // tiny-skia keeps premultiplied alpha; a PNG holds plain alpha, so undo it
    // here or every soft edge comes out dark.
    let mut pixels = Vec::with_capacity((size * size * 4) as usize);
    for pixel in pixmap.pixels() {
        let color = if pixel.alpha() == 0 {
            resvg::tiny_skia::ColorU8::from_rgba(0, 0, 0, 0)
        } else {
            pixel.demultiply()
        };
        pixels.extend_from_slice(&[color.red(), color.green(), color.blue(), pixel.alpha()]);
    }
    let image = image::RgbaImage::from_raw(size, size, pixels)
        .unwrap_or_else(|| panic!("{} did not fill a {size}×{size} image", svg.display()));
    let mut png = Vec::new();
    image
        .write_to(&mut std::io::Cursor::new(&mut png), image::ImageFormat::Png)
        .unwrap_or_else(|error| panic!("encoding {} as PNG: {error}", svg.display()));
    png
}

/// The app icon in `retinue-native.exe`, so Explorer, the Start menu shortcut
/// and the taskbar show the Retinue mark rather than a blank document.
///
/// The checkout path contains an apostrophe, which Windows' resource compiler
/// objects to on some machines; the icon is cosmetic, so a failure is a warning
/// and the package script builds from a short path when it can.
fn embed_icon(repo: &Path, out: &Path) {
    let icon = repo.join("assets").join("icon").join("retinue.ico");
    if !icon.is_file() {
        println!("cargo:warning=assets/icon/retinue.ico is missing; the app has no icon");
        return;
    }
    println!("cargo:rerun-if-changed={}", icon.display());
    let rc = out.join("retinue-native.rc");
    let escaped = icon.to_string_lossy().replace('\\', "\\\\");
    fs::write(&rc, format!("1 ICON \"{escaped}\"\n")).expect("writing the app icon resource");
    match embed_resource::compile(&rc, embed_resource::NONE).manifest_optional() {
        Ok(()) => {}
        Err(error) => println!("cargo:warning=the app icon was not embedded: {error}"),
    }
}
